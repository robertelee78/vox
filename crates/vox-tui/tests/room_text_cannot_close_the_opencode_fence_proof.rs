const VOX: &str = env!("CARGO_BIN_EXE_vox");

/// `vox` against this profile, with `input` on stdin.
fn vox(data: &Path, cfg: &Path, args: &[&str], input: &str) -> (bool, String, String) {
    let mut c = Command::new(VOX);
    c.args(args)
        .env_clear()
        .env("PATH", std::env::var_os("PATH").unwrap_or_default())
        .env(
            "HOME",
            cfg.parent().expect("APPARATUS: scratch root").join("home"),
        )
        .env("VOX_TEST_KEYCHAIN", unlock_staging::keychain(data))
        .env("VOX_DATA_DIR", data)
        .env("VOX_CONFIG_DIR", cfg)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    let mut child = c.spawn().expect("APPARATUS: cannot start vox");
    child
        .stdin
        .take()
        .expect("APPARATUS: vox has no stdin")
        .write_all(input.as_bytes())
        .expect("APPARATUS: cannot write vox's stdin");
    let out = child
        .wait_with_output()
        .expect("APPARATUS: cannot wait for vox");
    (
        out.status.success(),
        String::from_utf8_lossy(&out.stdout).into_owned(),
        String::from_utf8_lossy(&out.stderr).into_owned(),
    )
}

/// A program on `PATH`, as a shell would find it.
fn which(bin: &str) -> Option<PathBuf> {
    std::env::var_os("PATH").and_then(|p| {
        std::env::split_paths(&p)
            .map(|d| d.join(bin))
            .find(|c| c.is_file())
    })
}

/// A child killed with this proof, by its own handle.
struct Killed(Child);

impl Killed {
    fn stop(&mut self) {
        self.0
            .kill()
            .expect("APPARATUS: stop the owned scratch daemon");
        self.0
            .wait()
            .expect("APPARATUS: reap the owned scratch daemon");
    }
}

impl Drop for Killed {
    fn drop(&mut self) {
        let _ = self.0.kill();
        let _ = self.0.wait();
    }
}

/// The plugin as OpenCode runs it (`support/opencode_plugin_host.mjs`), one JSON line per command.
struct Host {
    child: Killed,
    lines: std::sync::mpsc::Receiver<String>,
}

impl Host {
    fn start(node: &Path, plugin: &Path, session: &str, project: &Path, root: &Path) -> Self {
        std::fs::create_dir_all(project).expect("APPARATUS: scratch session directory");
        let host_js =
            Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/support/opencode_plugin_host.mjs");
        let mut child = Command::new(node)
            .arg(host_js)
            .arg(plugin)
            .arg(session)
            .current_dir(project)
            .env_clear()
            .env("PATH", "/usr/bin:/bin")
            .env("HOME", root.join("home"))
            .env("TMPDIR", root.join("tmp"))
            .env("VOX_BIN", VOX)
            .env("VOX_DATA_DIR", root.join("data"))
            .env("VOX_CONFIG_DIR", root.join("cfg"))
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::inherit())
            .spawn()
            .expect("APPARATUS: start generated plugin host");
        let out = child.stdout.take().expect("APPARATUS: the host's stdout");
        let (tx, lines) = std::sync::mpsc::channel();
        std::thread::spawn(move || {
            use std::io::BufRead as _;
            for line in std::io::BufReader::new(out).lines().map_while(Result::ok) {
                if tx.send(line).is_err() {
                    break;
                }
            }
        });
        Self {
            child: Killed(child),
            lines,
        }
    }

    fn quiet(&mut self, why: &str) {
        let got = self.ask("wake 6", Duration::from_secs(15));
        assert_eq!(
            got["kind"], "no-wake",
            "PRODUCT: {why}; plugin received {got}"
        );
    }

    fn room_wake(&mut self, room: &str, body: &str, foreign: &str) {
        let got = self.ask("wake 60", Duration::from_secs(75));
        assert_eq!(
            got["kind"], "wake",
            "PRODUCT: {room}'s session was not woken for {body}: {got}"
        );
        let notice = got["relayed"].as_str().unwrap_or_default();
        let text = got["text"].as_str().unwrap_or_default();
        assert!(
            notice.contains(room) && !notice.contains(foreign),
            "PRODUCT: the relayed notice must name only saved room {room}: {got}"
        );
        assert!(
            text.contains(body) && !text.contains(foreign),
            "PRODUCT: the woken turn must read only saved room {room}: {got}"
        );
        println!("[proof] #795 {room}: {body}; notice={notice:?}");
    }

    fn ask(&mut self, command: &str, within: Duration) -> serde_json::Value {
        let stdin = self
            .child
            .0
            .stdin
            .as_mut()
            .expect("APPARATUS: the host's stdin");
        writeln!(stdin, "{command}").expect("APPARATUS: write to the host");
        let line = self.lines.recv_timeout(within).unwrap_or_else(|e| {
            panic!("APPARATUS: the plugin host did not answer {command:?} within {within:?}: {e}")
        });
        let v: serde_json::Value = serde_json::from_str(&line)
            .unwrap_or_else(|e| panic!("APPARATUS: the plugin host said {line:?}: {e}"));
        assert_ne!(
            v["kind"], "apparatus",
            "APPARATUS: the plugin host could not do {command:?}: {v}"
        );
        v
    }
}

/// Vox's notice block the plugin put first, if any: (nonce, what is inside, what follows it).
fn notice(given: &str) -> Option<(String, String, String)> {
    let rest = given.strip_prefix("<vox-notice-")?;
    let (nonce, rest) = rest.split_once(' ')?;
    let (_, inside) = rest.split_once(">\n")?;
    let close = format!("\n</vox-notice-{nonce}>\n\n");
    let (inside, after) = inside.split_once(&close)?;
    Some((nonce.to_owned(), inside.to_owned(), after.to_owned()))
}

/// The fence the plugin put in front of the typed text, after Vox's notice block if there is one:
/// (nonce, what is inside, what follows the closing tag). `None` when there is no fence of the
/// plugin's shape.
fn fence(given: &str) -> Option<(String, String, String)> {
    let given = notice(given).map_or(given.to_owned(), |(_, _, after)| after);
    let rest = given.strip_prefix("<vox-room-")?;
    let (nonce, rest) = rest.split_once(' ')?;
    let (_, inside) = rest.split_once(">\n")?;
    let close = format!("\n</vox-room-{nonce}>\n\n");
    let (inside, after) = inside.split_once(&close)?;
    Some((nonce.to_owned(), inside.to_owned(), after.to_owned()))
}

